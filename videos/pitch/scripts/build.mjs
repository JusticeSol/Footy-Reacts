import { writeFileSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const LEAD = 0.6; // narration starts here
const VOICE = +execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
  new URL("../assets/voice/narration.wav", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1").replace(/%20/g, " ")]).toString().trim();
const TOTAL = Math.round((LEAD + VOICE + 2.0) * 10) / 10; // the end card holds 2s after the last word
const words = JSON.parse(readFileSync(new URL("../work/words.json", import.meta.url))).map((w) => ({
  ...w, start: w.start + LEAD, end: w.end + LEAD,
}));

// global time of the first word matching `text` in section s, optionally after time `after`
function at(s, text, after = 0) {
  const w = words.find((x) => x.s === s && x.start >= after && x.text.toLowerCase().replace(/[^a-z0-9']/g, "") === text);
  if (!w) throw new Error(`no word "${text}" in section ${s}`);
  return w.start;
}

