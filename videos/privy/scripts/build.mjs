// frame-local time of the first spoken word matching `text` (after `after`)
function word(id, text, after = 0) {
  const w = voice[id].words.find((x) => x.start >= after && x.text.toLowerCase().replace(/[^a-z0-9]/g, "").startsWith(text));
  if (!w) throw new Error(`${id}: no word "${text}"`);
  return r(VO + w.start);
}

